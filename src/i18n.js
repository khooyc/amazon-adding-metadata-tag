  const supportedLocales = ['en', 'zh-CN', 'zh-TW'];

  function normalizeLocale(locale) {
    const value = String(locale || '').toLowerCase();
    if (value.startsWith('zh-tw') || value.startsWith('zh-hk') || value.startsWith('zh-mo') || value.includes('hant')) return 'zh-TW';
    if (value.startsWith('zh') || value.includes('hans')) return 'zh-CN';
    return 'en';
  }

  function translate(locale, key, variables = {}) {
    const selected = supportedLocales.includes(locale) ? locale : normalizeLocale(locale);
    const template = translations[selected]?.[key] ?? translations.en[key] ?? key;
    return String(template).replace(/\{(\w+)\}/g, (_match, name) => String(variables[name] ?? `{${name}}`));
  }

  window.appI18n = Object.freeze({ translations, supportedLocales, normalizeLocale, translate });
